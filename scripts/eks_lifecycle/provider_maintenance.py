#!/usr/bin/env python3
"""Render the reviewed management Provider bundle without calling cluster or AWS APIs."""
from __future__ import annotations

import argparse
import json
import re
import sys

from common import EKS_ROOT, LOCK_FILE, ToolError, load_yaml
import manage_provider_rbac as rbac


ROOT = EKS_ROOT / "management-auth"
PROVIDERS_FILE = ROOT / "providers.yaml"
PROVIDER_CONFIG_TEMPLATE = EKS_ROOT / "management-aws-auth" / "provider-config.template.yaml"
DNS_LABEL = re.compile(r"^[a-z0-9](?:[-a-z0-9]{0,61}[a-z0-9])?$")
LABEL_PREFIX = "platform.aws.goodnotes.io/"
DEPENDENCY_FILES = {
    "upbound-provider-aws-sqs": EKS_ROOT / "dependencies" / "provider-aws-sqs.yaml",
    "upbound-provider-aws-cloudwatchevents": (
        EKS_ROOT / "dependencies" / "provider-aws-cloudwatchevents.yaml"
    ),
}


def contract(lock: dict | None = None) -> dict:
    result = rbac.inventory()
    packages = (lock if lock is not None else load_yaml(LOCK_FILE)).get("packages", {})
    for provider in result["providers"]:
        locked = packages.get(provider["lockKey"])
        if not isinstance(locked, dict):
            raise ToolError("Provider inventory references a missing package lock")
        if (
            locked.get("reference") != provider["package"]
            or locked.get("version") != provider["version"]
        ):
            raise ToolError("Provider inventory differs from versions.lock.yaml")
    expected = {item["metadata"]["name"]: item for item in provider_documents(result)}
    for name, path in DEPENDENCY_FILES.items():
        if load_yaml(path) != expected[name]:
            raise ToolError("dependency Provider differs from the maintenance inventory")
    return result


def provider_documents(reviewed: dict) -> list[dict]:
    documents = []
    for provider in reviewed["providers"]:
        session_consumer = provider["runtimeConfig"] != rbac.RUNTIME_DEFAULT
        documents.append({
            "apiVersion": "pkg.crossplane.io/v1",
            "kind": "Provider",
            "metadata": {
                "name": provider["name"],
                "annotations": {LABEL_PREFIX + "version": provider["version"]},
                "labels": {
                    LABEL_PREFIX + "managed-by": "platform-bootstrap",
                    LABEL_PREFIX + "resource-role": (
                        "on-demand-session-provider" if session_consumer else "shared-provider"
                    ),
                    LABEL_PREFIX + "session-consumer": str(session_consumer).lower(),
                },
            },
            "spec": {
                "package": provider["package"],
                "packagePullPolicy": "IfNotPresent",
                "revisionActivationPolicy": "Automatic",
                "revisionHistoryLimit": 2,
                "runtimeConfigRef": {
                    "apiVersion": "pkg.crossplane.io/v1beta1",
                    "kind": "DeploymentRuntimeConfig",
                    "name": provider["runtimeConfig"],
                },
            },
        })
    return documents


def yaml_bytes(documents: list[dict], header: str = "") -> bytes:
    payload = "\n---\n".join(json.dumps(document) for document in documents).encode()
    rendered = rbac.maintenance.run(["yq", "eval", "-P", ".", "-"], payload)
    return header.encode() + rendered


def rendered_bytes(reviewed: dict) -> bytes:
    return yaml_bytes(
        provider_documents(reviewed),
        "# Generated by scripts/eks_lifecycle/provider_maintenance.py; do not hand edit.\n",
    )


def provider_config(name: str) -> dict:
    if not DNS_LABEL.fullmatch(name):
        raise ToolError("ProviderConfig name must be a DNS label")
    document = load_yaml(PROVIDER_CONFIG_TEMPLATE)
    document["metadata"]["name"] = name
    annotations = document["metadata"].get("annotations", {})
    annotations.pop(LABEL_PREFIX + "do-not-apply", None)
    if annotations:
        document["metadata"]["annotations"] = annotations
    else:
        document["metadata"].pop("annotations", None)
    return document


def public_plan(reviewed: dict) -> dict:
    providers = reviewed["providers"]
    return {
        "mode": "plan",
        "providerCount": len(providers),
        "sessionConsumerCount": sum(
            p["runtimeConfig"] != rbac.RUNTIME_DEFAULT for p in providers
        ),
        "sessionSecretReaderCount": sum(p["sessionReader"] for p in providers),
        "runtimeBindings": {p["name"]: p["runtimeConfig"] for p in providers},
        "packageDigestsPinned": True,
        "awsMutation": False,
        "kubernetesMutation": False,
        "startsControllers": False,
        "publishesCredentials": False,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("plan", "render", "provider-config"))
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--name")
    args = parser.parse_args(argv)
    try:
        reviewed = contract()
        if args.mode == "plan":
            if args.check or args.name:
                raise ToolError("plan does not accept render options")
            print(json.dumps(public_plan(reviewed), indent=2, sort_keys=True))
        elif args.mode == "render":
            if args.name:
                raise ToolError("render does not accept a ProviderConfig name")
            output = rendered_bytes(reviewed)
            if args.check:
                if PROVIDERS_FILE.read_bytes() != output:
                    raise ToolError("management Provider bundle differs from reviewed inventory")
            else:
                PROVIDERS_FILE.write_bytes(output)
            print(
                json.dumps(
                    {
                        "providerDocuments": len(provider_documents(reviewed)),
                        "offline": True,
                    }
                )
            )
        else:
            if args.check or not args.name:
                raise ToolError("provider-config requires --name and does not accept --check")
            sys.stdout.buffer.write(yaml_bytes([provider_config(args.name)]))
        return 0
    except (ToolError, OSError, ValueError, KeyError, TypeError) as error:
        print(
            str(error)
            if isinstance(error, ToolError)
            else "provider maintenance preparation failed",
            file=sys.stderr,
        )
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
